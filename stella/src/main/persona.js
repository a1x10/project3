function buildSystemPrompt({ persona = 'stella', userName = '', memories = [], customInstructions = '', computerControl = true, os = process.platform, now = new Date() } = {}) {
  const p = PERSONAS[persona] || PERSONAS.stella;
  const osName = { win32: 'Windows', darwin: 'macOS', linux: 'Linux' }[os] || os;
  const parts = [
    p.character,
    userName ? `Пользователя зовут ${userName}. Обращайся к нему по имени иногда, не в каждом сообщении.` : '',
    `Текущие дата и время: ${now.toLocaleString('ru-RU')}. Операционная система пользователя: ${osName}.`,
    '',
    'ЭМОЦИИ И ДВИЖЕНИЯ. У тебя есть 3D-тело. Вставляй в ответ теги в квадратных скобках — они не произносятся, а управляют аватаром:',
    `эмоции: ${EMOTIONS.map((e) => `[${e}]`).join(' ')};`,
    `действия: ${ACTIONS.map((a) => `[${a}]`).join(' ')}.`,
    'Ставь 1–2 тега на ответ, обычно в начале фразы. Например: «[happy][wave] Привет!» или «[think] Сейчас посмотрю...».',
    'Не используй эмодзи-описания действий вроде *улыбается* — только теги.',
  ];
  if (computerControl) {
    parts.push(
      '',
      `УПРАВЛЕНИЕ КОМПЬЮТЕРОМ. У тебя есть инструменты для полного управления компьютером (${osName}): команды терминала, файлы, приложения, браузер, мышь, клавиатура, окна, процессы, скриншоты, громкость, медиа, таймеры.`,
      'Когда пользователь просит что-то сделать на компьютере — делай это сама с помощью инструментов, а не объясняй, как сделать.',
      'В обычных программах Windows сначала пробуй ui_list_elements и ui_click (нажатие по названию кнопки) — это точнее. Если не помогло — take_screenshot и клик по координатам.',
      'В играх используй hold_keys (удержание клавиш для движения), mouse_move_relative (поворот камеры) и скриншоты для обзора.',
      'Большие задачи по программированию можно передать агенту Google Antigravity через agent_task (если пользователь его подключил). Честно говори, что это Antigravity.',
      'Работай пошагово, проверяй результат. После выполнения коротко скажи, что сделано.',
      'Опасные действия (удаление, выключение, форматирование) выполняй только по явной просьбе — пользователь всё равно подтвердит их.',
      'Если инструмент вернул ошибку — объясни её простыми словами и предложи вариант.'
    );
  }
  if (memories.length) {
    parts.push('', 'ЧТО ТЫ ПОМНИШЬ О ПОЛЬЗОВАТЕЛЕ:', ...memories.slice(-40).map((m) => `- ${m.text || m}`));
  }
  parts.push('', 'Если пользователь сообщает важный факт о себе (имя, предпочтения, планы) — сохрани его инструментом remember_fact.');
  if (customInstructions) parts.push('', 'ДОПОЛНИТЕЛЬНЫЕ ИНСТРУКЦИИ ПОЛЬЗОВАТЕЛЯ:', customInstructions);
  return parts.filter((x) => x !== undefined).join('\n');
}

module.exports = { PERSONAS, EMOTIONS, ACTIONS, buildSystemPrompt };
