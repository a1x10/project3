#!/usr/bin/env node
// FreeLLMAPI router manager shared by the installer, STELLA CODER and Vibing AI Studio.
// Dependency-free, cross-platform (Linux, macOS, Windows).
//
//   Docker/Podman mode — same layout as the official installer (https://freellmapi.co/install.sh):
//     ~/freellmapi/.env + docker-compose.yml, image ghcr.io/tashfeenahmed/freellmapi:latest
//   Source mode (no container engine) — git clone into ~/freellmapi/app, npm ci, npm run build,
//     node server/dist/index.js as a background process.
//
// CLI: node tools/freellmapi-router.mjs <install|start|stop|status|ensure|logs|connect|key> [--mode docker|source]
import { spawn, spawnSync } from "node:child_process";
import { randomBytes } from "node:crypto";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

export const IMAGE = "ghcr.io/tashfeenahmed/freellmapi:latest";
export const REPO = "https://github.com/tashfeenahmed/freellmapi.git";
export const TARBALL = "https://codeload.github.com/tashfeenahmed/freellmapi/tar.gz/refs/heads/main";
const IS_WIN = process.platform === "win32";

export function routerConfig(env = process.env) {
  const port = Number(env.FREELLMAPI_PORT || 3001);
  const dir = path.resolve(env.FREELLMAPI_DIR || path.join(os.homedir(), "freellmapi"));
  return {
    dir,
    port,
    hostBind: env.FREELLMAPI_HOST_BIND || "127.0.0.1",
    url: `http://127.0.0.1:${port}`,
    appDir: path.join(dir, "app"),
    stateFile: path.join(dir, "stella-router.json"),
    pidFile: path.join(dir, "router.pid"),
    logFile: path.join(dir, "router.log"),
  };
}

export function stellaHome(env = process.env) {
  return env.STELLA_HOME ? path.resolve(env.STELLA_HOME) : path.join(os.homedir(), ".stella");
}

// ---------------------------------------------------------------- helpers

function readJson(file, fallback) {
  try {
    return JSON.parse(fs.readFileSync(file, "utf8"));
  } catch {
    return fallback;
  }
}

function writeJson(file, value, mode) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, JSON.stringify(value, null, 2) + "\n", mode ? { mode } : undefined);
  if (mode && !IS_WIN) fs.chmodSync(file, mode);
}

function which(cmd) {
  const exts = IS_WIN ? (process.env.PATHEXT || ".EXE;.CMD;.BAT").split(";") : [""];
  for (const dir of (process.env.PATH || "").split(path.delimiter)) {
    if (!dir) continue;
    for (const ext of exts) {
      const p = path.join(dir, cmd + ext);
      try {
        fs.accessSync(p, IS_WIN ? fs.constants.F_OK : fs.constants.X_OK);
        return p;
      } catch {
        /* next */
      }
    }
  }
  return null;
}

function run(cmd, args, opts = {}) {
  // .cmd/.bat shims (npm on Windows) need a shell; everything else runs without one.
  const shell = IS_WIN && /\.(cmd|bat)$/i.test(cmd);
  const r = spawnSync(cmd, args, { stdio: opts.quiet ? "pipe" : "inherit", cwd: opts.cwd, env: { ...process.env, ...(opts.env || {}) }, shell, windowsHide: true, timeout: opts.timeoutMs });
  return { ok: r.status === 0, status: r.status, stdout: r.stdout?.toString() ?? "", stderr: r.stderr?.toString() ?? "", error: r.error };
}

const noop = () => {};

export async function ping(cfg = routerConfig(), timeoutMs = 1500) {
  try {
    const r = await fetch(`${cfg.url}/api/ping`, { signal: AbortSignal.timeout(timeoutMs) });
    return r.ok;
  } catch {
    return false;
  }
}

export async function waitReady(cfg = routerConfig(), timeoutMs = 90_000) {
  const t0 = Date.now();
  while (Date.now() - t0 < timeoutMs) {
    if (await ping(cfg)) return true;
    await new Promise((r) => setTimeout(r, 1000));
  }
  return false;
}

/** Docker or Podman with a compose front-end and a running daemon. */
export function detectEngine() {
  for (const engine of ["docker", "podman"]) {
    const bin = which(engine);
    if (!bin) continue;
    let compose = null;
    if (run(bin, ["compose", "version"], { quiet: true }).ok) compose = [bin, "compose"];
    else if (which(`${engine}-compose`)) compose = [which(`${engine}-compose`)];
    if (!compose) continue;
    const running = run(bin, ["info"], { quiet: true, timeoutMs: 20_000 }).ok;
    return { engine, bin, compose, running };
  }
  return null;
}

function compose(engine, args, cfg, opts = {}) {
  const [bin, ...pre] = engine.compose;
  return run(bin, [...pre, ...args], { cwd: cfg.dir, ...opts });
}

function ensureEnvFile(cfg) {
  const file = path.join(cfg.dir, ".env");
  fs.mkdirSync(cfg.dir, { recursive: true });
  if (fs.existsSync(file)) return file;
  const content = [
    `# Generated by the STELLA/Vibing installer on ${new Date().toISOString()}`,
    "# At-rest encryption key for your stored provider keys. Losing it means re-entering them — back this file up.",
    `ENCRYPTION_KEY=${randomBytes(32).toString("hex")}`,
    `PORT=${cfg.port}`,
    `HOST_BIND=${cfg.hostBind}`,
    "",
  ].join("\n");
  fs.writeFileSync(file, content, { mode: 0o600 });
  return file;
}

export function readEnvFile(cfg) {
  const out = {};
  try {
    for (const line of fs.readFileSync(path.join(cfg.dir, ".env"), "utf8").split(/\r?\n/)) {
      const m = /^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)\s*$/.exec(line);
      if (m) out[m[1]] = m[2].replace(/^["']|["']$/g, "");
    }
  } catch {
    /* none */
  }
  return out;
}

function writeComposeFile(cfg) {
  // Identical to the official installer's compose file, so both tools manage the same install.
  const yml = `# Written by the STELLA/Vibing installer (compatible with freellmapi.co/install.sh).
services:
  freellmapi:
    image: ${IMAGE}
    env_file:
      - .env
    environment:
      NODE_ENV: production
      PORT: 3001
    ports:
      - "\${HOST_BIND:-127.0.0.1}:\${PORT:-3001}:3001"
    volumes:
      - freellmapi-data:/app/server/data
    restart: unless-stopped
    healthcheck:
      test: ["CMD", "node", "-e", "fetch('http://127.0.0.1:3001/api/ping').then((r)=>{if(!r.ok)process.exit(1)}).catch(()=>process.exit(1))"]
      interval: 30s
      timeout: 5s
      start_period: 15s
      retries: 3

volumes:
  freellmapi-data:
`;
  fs.writeFileSync(path.join(cfg.dir, "docker-compose.yml"), yml);
}

export function installedMode(cfg = routerConfig()) {
  const state = readJson(cfg.stateFile, null);
  if (state?.mode) return state.mode;
  if (fs.existsSync(path.join(cfg.dir, "docker-compose.yml"))) return "docker"; // official installer
  if (fs.existsSync(path.join(cfg.appDir, "server", "dist", "index.js"))) return "source";
  return null;
}

// ---------------------------------------------------------------- install / start / stop

/** Node versions the router supports when built from source (its package.json engines). */
export function nodeSupportsSource(version = process.versions.node) {
  const [major, minor] = version.split(".").map(Number);
  return !(major < 20 || (major === 20 && minor < 18) || major >= 25);
}

/** Launch Docker Desktop (Windows/macOS) and wait until the daemon answers. */
export async function startDockerDesktop({ log = noop, timeoutMs = 180_000 } = {}) {
  let launched = false;
  if (IS_WIN) {
    const candidates = [process.env.ProgramFiles, process.env["ProgramFiles(x86)"], process.env.LOCALAPPDATA]
      .filter(Boolean)
      .map((d) => path.join(d, "Docker", "Docker", "Docker Desktop.exe"));
    const exe = candidates.find((p) => fs.existsSync(p));
    if (exe) {
      spawn(exe, [], { detached: true, stdio: "ignore", windowsHide: true }).unref();
      launched = true;
    }
  } else if (process.platform === "darwin") {
    launched = run("open", ["-a", "Docker"], { quiet: true }).ok;
  }
  if (!launched) return false;
  log("Запускаю Docker Desktop и жду, пока он будет готов (до 3 минут)…");
  const t0 = Date.now();
  while (Date.now() - t0 < timeoutMs) {
    const eng = detectEngine();
    if (eng?.running) return true;
    await new Promise((r) => setTimeout(r, 3000));
  }
  return false;
}

export async function install(cfg = routerConfig(), { mode = "auto", log = noop } = {}) {
  if (mode === "auto" || mode === "docker") {
    let eng = detectEngine();
    if (eng && !eng.running && (await startDockerDesktop({ log }))) eng = detectEngine();
    if (mode === "auto") {
      if (eng?.running) mode = "docker";
      else if (nodeSupportsSource()) {
        if (eng) log(`${eng.engine} установлен, но не запущен — ставлю роутер из исходников.`);
        mode = "source";
      } else {
        throw new Error(
          `Для сборки роутера из исходников нужен Node.js 20.18–24 (сейчас ${process.versions.node}), а Docker ${eng ? "не запущен" : "не установлен"}. ` +
            (eng
              ? "Запустите Docker Desktop и повторите: node install.mjs --router-mode docker"
              : "Установите Docker Desktop (winget install Docker.DockerDesktop) или Node.js 22 LTS (winget install OpenJS.NodeJS.LTS) и повторите установку.")
        );
      }
    }
  }
  fs.mkdirSync(cfg.dir, { recursive: true });
  ensureEnvFile(cfg);
  if (mode === "docker") {
    const eng = detectEngine();
    if (!eng) throw new Error("Docker или Podman не найдены.");
    if (!eng.running) throw new Error(`${eng.engine} не запущен. Запустите Docker Desktop (дождитесь «Engine running») и повторите: node install.mjs --router-mode docker`);
    writeComposeFile(cfg);
    log(`Скачиваю образ ${IMAGE}…`);
    if (!compose(eng, ["pull"], cfg).ok) throw new Error("Не удалось скачать образ роутера.");
    log("Запускаю контейнер…");
    if (!compose(eng, ["up", "-d"], cfg).ok) throw new Error("Не удалось запустить контейнер роутера.");
  } else if (mode === "source") {
    if (!nodeSupportsSource()) throw new Error(`Для сборки роутера из исходников нужен Node.js 20.18–24 (сейчас ${process.versions.node}). Используйте Docker: node install.mjs --router-mode docker, или поставьте Node.js 22 LTS.`);
    await fetchSource(cfg, log);
    const npm = which("npm");
    if (!npm) throw new Error("npm не найден.");
    log("Устанавливаю зависимости роутера (npm ci)…");
    if (!run(npm, ["ci", "--no-audit", "--no-fund"], { cwd: cfg.appDir }).ok) throw new Error("npm ci для роутера завершился с ошибкой (см. вывод выше).");
    log("Собираю роутер (npm run build)…");
    if (!run(npm, ["run", "build"], { cwd: cfg.appDir }).ok) throw new Error("Сборка роутера завершилась с ошибкой (см. вывод выше).");
  } else throw new Error(`Неизвестный режим ${mode}`);
  writeJson(cfg.stateFile, { mode, installedAt: new Date().toISOString(), port: cfg.port });
  if (mode === "source") await start(cfg, { log });
  log("Жду, пока роутер ответит…");
  if (!(await waitReady(cfg))) throw new Error(`Роутер не ответил на ${cfg.url}/api/ping. Логи: node tools/freellmapi-router.mjs logs`);
  return mode;
}

async function fetchSource(cfg, log) {
  const git = which("git");
  if (fs.existsSync(path.join(cfg.appDir, ".git")) && git) {
    log("Обновляю исходники роутера (git pull)…");
    run(git, ["-C", cfg.appDir, "pull", "--ff-only"], { quiet: true });
    return;
  }
  if (fs.existsSync(path.join(cfg.appDir, "package.json"))) return;
  if (git) {
    log(`Скачиваю исходники роутера (${REPO})…`);
    if (run(git, ["clone", "--depth", "1", REPO, cfg.appDir]).ok) return;
  }
  const tar = which("tar");
  if (!tar) throw new Error("Нужен git или tar, чтобы скачать роутер.");
  log("Скачиваю архив исходников роутера…");
  const res = await fetch(TARBALL);
  if (!res.ok) throw new Error(`Не удалось скачать ${TARBALL}: HTTP ${res.status}`);
  const archive = path.join(cfg.dir, "freellmapi-src.tar.gz");
  fs.writeFileSync(archive, Buffer.from(await res.arrayBuffer()));
  fs.mkdirSync(cfg.appDir, { recursive: true });
  if (!run(tar, ["-xzf", archive, "-C", cfg.appDir, "--strip-components=1"]).ok) throw new Error("Не удалось распаковать исходники роутера.");
  fs.rmSync(archive, { force: true });
}

function readPid(cfg) {
  const pid = Number(readJson(cfg.pidFile, {}).pid);
  if (!pid) return null;
  try {
    process.kill(pid, 0);
    return pid;
  } catch {
    return null;
  }
}

export async function start(cfg = routerConfig(), { log = noop, mode = installedMode(cfg) } = {}) {
  if (await ping(cfg)) return { started: false, running: true, mode };
  if (!mode) throw new Error("Роутер FreeLLMAPI не установлен. Запустите установщик (install.sh / install.ps1) или: node tools/freellmapi-router.mjs install");
  if (mode === "docker") {
    let eng = detectEngine();
    if (!eng) throw new Error("Docker/Podman не найдены, а роутер установлен как контейнер.");
    if (!eng.running && (await startDockerDesktop({ log }))) eng = detectEngine();
    if (!eng.running) throw new Error(`${eng.engine} не запущен — запустите Docker Desktop / службу docker.`);
    log("Запускаю контейнер FreeLLMAPI…");
    if (!compose(eng, ["up", "-d"], cfg, { quiet: true }).ok) throw new Error("docker compose up не удался.");
  } else {
    if (readPid(cfg)) return { started: false, running: await ping(cfg), mode };
    const entry = path.join(cfg.appDir, "server", "dist", "index.js");
    if (!fs.existsSync(entry)) throw new Error(`Не найден ${entry}. Переустановите роутер: node tools/freellmapi-router.mjs install --mode source`);
    log("Запускаю FreeLLMAPI в фоне…");
    const out = fs.openSync(cfg.logFile, "a");
    const env = { ...process.env, ...readEnvFile(cfg), NODE_ENV: "production", PORT: String(cfg.port), FREEAPI_ENV_PATH: path.join(cfg.dir, ".env") };
    const child = spawn(process.execPath, [entry], { cwd: cfg.appDir, env, detached: true, stdio: ["ignore", out, out], windowsHide: true });
    child.unref();
    writeJson(cfg.pidFile, { pid: child.pid, startedAt: new Date().toISOString() });
  }
  return { started: true, running: false, mode };
}

export async function stop(cfg = routerConfig()) {
  const mode = installedMode(cfg);
  if (mode === "docker") {
    const eng = detectEngine();
    if (eng) compose(eng, ["stop"], cfg, { quiet: true });
    return true;
  }
  const pid = readPid(cfg);
  if (!pid) return false;
  if (IS_WIN) spawnSync("taskkill", ["/pid", String(pid), "/T", "/F"], { windowsHide: true });
  else {
    try {
      process.kill(-pid, "SIGTERM");
    } catch {
      try {
        process.kill(pid, "SIGTERM");
      } catch {
        /* gone */
      }
    }
  }
  fs.rmSync(cfg.pidFile, { force: true });
  return true;
}

/** Start the router if it is installed but not running; never installs. */
export async function ensure(cfg = routerConfig(), { log = noop, timeoutMs = 60_000 } = {}) {
  if (await ping(cfg)) return { running: true, started: false };
  const mode = installedMode(cfg);
  if (!mode) return { running: false, started: false, reason: "not-installed" };
  try {
    await start(cfg, { log, mode });
  } catch (e) {
    return { running: false, started: false, reason: e.message };
  }
  const ok = await waitReady(cfg, timeoutMs);
  return { running: ok, started: true, mode, reason: ok ? undefined : `роутер не ответил за ${Math.round(timeoutMs / 1000)} с` };
}

export async function status(cfg = routerConfig()) {
  return { installed: !!installedMode(cfg), mode: installedMode(cfg), running: await ping(cfg), url: cfg.url, dashboard: cfg.url, dir: cfg.dir, keySaved: !!readRouterKey() };
}

export function logs(cfg = routerConfig(), lines = 80) {
  if (installedMode(cfg) === "docker") {
    const eng = detectEngine();
    return eng ? compose(eng, ["logs", "--tail", String(lines)], cfg, { quiet: true }).stdout : "";
  }
  try {
    return fs.readFileSync(cfg.logFile, "utf8").split("\n").slice(-lines).join("\n");
  } catch {
    return "";
  }
}

// ---------------------------------------------------------------- dashboard API

async function api(cfg, method, p, { token, body } = {}) {
  const res = await fetch(`${cfg.url}${p}`, {
    method,
    headers: { "content-type": "application/json", ...(token ? { authorization: `Bearer ${token}` } : {}) },
    body: body ? JSON.stringify(body) : undefined,
    signal: AbortSignal.timeout(20_000),
  });
  const text = await res.text();
  let json = null;
  try {
    json = text ? JSON.parse(text) : null;
  } catch {
    /* not json */
  }
  if (!res.ok) throw new Error(json?.error?.message || `HTTP ${res.status} ${p}`);
  return json;
}

export async function dashboardStatus(cfg = routerConfig()) {
  return api(cfg, "GET", "/api/auth/status");
}

/** First run: create the dashboard account (allowed from this machine without a code). Later: log in. */
export async function connect(cfg, { email, password }) {
  const st = await dashboardStatus(cfg);
  const r = st.needsSetup ? await api(cfg, "POST", "/api/auth/setup", { body: { email, password } }) : await api(cfg, "POST", "/api/auth/login", { body: { email, password } });
  return { token: r.token, created: !!st.needsSetup };
}

export async function getUnifiedKey(cfg, token) {
  return (await api(cfg, "GET", "/api/settings/api-key", { token })).apiKey;
}

export async function listProviders(cfg, token) {
  return (await api(cfg, "GET", "/api/keys/providers", { token })).providers;
}

export async function addProviderKey(cfg, token, platform, key) {
  return api(cfg, "POST", "/api/keys", { token, body: key ? { platform, key } : { platform } });
}

/** Turn on every provider that works without an API key, so the router answers right away. */
export async function enableKeylessProviders(cfg, token) {
  const providers = await listProviders(cfg, token);
  const added = [];
  for (const p of providers) {
    if (p.keyless && !p.configured && p.kind !== "search") {
      try {
        await addProviderKey(cfg, token, p.platform);
        added.push(p.name || p.platform);
      } catch {
        /* skip */
      }
    }
  }
  return added;
}

export async function validateKey(cfg, key) {
  try {
    const r = await fetch(`${cfg.url}/v1/models`, { headers: { authorization: `Bearer ${key}` }, signal: AbortSignal.timeout(10_000) });
    return r.ok;
  } catch {
    return false;
  }
}

// ---------------------------------------------------------------- shared credentials (~/.stella/credentials.json)

const credFile = () => path.join(stellaHome(), "credentials.json");

export function readRouterKey() {
  return process.env.FREELLMAPI_API_KEY || readJson(credFile(), {})["freellmapi.apiKey"] || "";
}

export function saveRouterKey(key) {
  const creds = readJson(credFile(), {});
  creds["freellmapi.apiKey"] = key;
  writeJson(credFile(), creds, 0o600);
}

// ---------------------------------------------------------------- CLI

export async function cli(argv) {
  const [cmd = "status", ...rest] = argv;
  const flag = (name) => {
    const i = rest.indexOf(`--${name}`);
    return i >= 0 ? rest[i + 1] : undefined;
  };
  const cfg = routerConfig();
  const log = (m) => console.log(`==> ${m}`);
  switch (cmd) {
    case "install":
      console.log(`FreeLLMAPI установлен (${await install(cfg, { mode: flag("mode") || "auto", log })}), ${cfg.url}`);
      break;
    case "start":
    case "ensure": {
      const r = await ensure(cfg, { log });
      console.log(r.running ? `FreeLLMAPI работает: ${cfg.url}` : `FreeLLMAPI не запущен: ${r.reason}`);
      process.exitCode = r.running ? 0 : 1;
      break;
    }
    case "stop":
      console.log((await stop(cfg)) ? "FreeLLMAPI остановлен" : "FreeLLMAPI не был запущен этим инструментом");
      break;
    case "logs":
      console.log(logs(cfg, Number(flag("lines") || 80)));
      break;
    case "key":
      if (rest[0] && !rest[0].startsWith("--")) {
        saveRouterKey(rest[0]);
        console.log(`Ключ сохранён в ${credFile()}`);
      } else console.log(readRouterKey() ? "Ключ сохранён" : "Ключ не сохранён");
      break;
    case "connect": {
      const email = flag("email");
      const password = flag("password");
      if (!email || !password) throw new Error("connect --email <почта> --password <пароль>");
      const { token, created } = await connect(cfg, { email, password });
      const key = await getUnifiedKey(cfg, token);
      saveRouterKey(key);
      const keyless = await enableKeylessProviders(cfg, token);
      console.log(`${created ? "Аккаунт дашборда создан. " : ""}Единый ключ сохранён.${keyless.length ? ` Включены бесплатные провайдеры без ключа: ${keyless.join(", ")}.` : ""}`);
      break;
    }
    default: {
      const s = await status(cfg);
      console.log(JSON.stringify(s, null, 2));
    }
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  cli(process.argv.slice(2)).catch((e) => {
    console.error(`Ошибка: ${e.message}`);
    process.exit(1);
  });
}
