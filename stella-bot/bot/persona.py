def daily_mood(chat_id: int, day: date) -> str:
    """Своё настроение на каждый день — одно и то же в течение дня, у каждого чата своё."""
    rng = random.Random(f"{chat_id}:{day.isoformat()}")
    moods = [m for m, _ in DAILY_MOODS]
    weights = [w for _, w in DAILY_MOODS]
    return rng.choices(moods, weights=weights, k=1)[0]


def current_mood(chat: dict[str, Any], tz_name: str, now: datetime | None = None) -> str:
    now = now or datetime.now(timezone.utc).replace(tzinfo=None)
    if chat.get("mood") and chat.get("mood_until") and chat["mood_until"] > now:
        return str(chat["mood"])
    local_day = now.replace(tzinfo=timezone.utc).astimezone(ZoneInfo(tz_name)).date()
    return daily_mood(int(chat.get("id") or 0), local_day)


