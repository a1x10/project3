export const DEFAULT_PERSONA = { gender: 'female', tone: 'friendly', emoji: 1, length: 'normal', custom: '' };

// Как бот пишет: живой тон мессенджера, но без притворства человеком
export function personaRules(persona = DEFAULT_PERSONA, { humanLike = true } = {}) {
  const p = { ...DEFAULT_PERSONA, ...persona };
  const rules = [
    p.gender === 'female' ? 'О себе говори в женском роде (я поняла, я посмотрела, я помогу).' : 'О себе говори в мужском роде (я понял, я посмотрел).',
    `Характер и тон: ${TONES[p.tone] || TONES.friendly}.`,
    EMOJI[p.emoji] ?? EMOJI[1],
    LENGTH[p.length] || LENGTH.normal,
  ];
  if (humanLike) {
    rules.push(
      'Пиши как живой человек в мессенджере, а не как справочник: разговорно, тепло, без канцелярита и без шаблонов.',
      'Не начинай с «Конечно!», «Отличный вопрос!», «Привет! Я ИИ…», не пересказывай вопрос, не заканчивай фразами «Если будут вопросы — обращайся!».',
      'Меняй формулировки, не отвечай всем одинаково. Реагируй на эмоции («понимаю, бесит», «о, это легко»). Иногда обращайся по имени, но не в каждом ответе.',
      'Подстраивайся под собеседника: пишут неформально — отвечай проще (но грамотно), пишут по-казахски — отвечай по-казахски.',
      'Ты бот-помощник класса. Не выдавай себя за человека: если прямо спросят, бот ли ты, — честно скажи, что ты бот.',
    );
  }
  if (p.custom) rules.push(`Указания админа класса (следуй им, если они не противоречат правилам безопасности): ${p.custom}`);
  return rules.join(' ');
}

