  инфа: 'информатика', информатику: 'информатика',
  англ: 'английский', инглиш: 'английский', english: 'английский', английскому: 'английский', ағылшын: 'ағылшын',
  каз: 'казахский', казак: 'казахский', казахскому: 'казахский', қазақ: 'қазақ',
  рус: 'русский', русскому: 'русский', русич: 'русский',
  лит: 'литература', литра: 'литература', литературе: 'литература',
  ист: 'история', историю: 'история', истории: 'история',
  био: 'биология', биологию: 'биология', биологии: 'биология',
